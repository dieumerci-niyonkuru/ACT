<script>
(function() {
  // Matches card heights within each council carousel row independently,
  // so photo/name/title align across cards within that row regardless of
  // title text length (e.g. "Advisor" vs "Students' Welfare / Treasurer
  // International Student"). Each row is measured on its own — row 1 and
  // row 2 can legitimately end up at different heights from each other.
  function matchCardHeightsIn(carouselId) {
    var carousel = document.getElementById(carouselId);
    if (!carousel) {
      return;
    }
    var cards = carousel.querySelectorAll('.hover-effect');
    if (!cards.length) {
      return;
    }
    cards.forEach(function(card) {
      card.style.height = 'auto';
    });
    var maxHeight = 0;
    cards.forEach(function(card) {
      maxHeight = Math.max(maxHeight, card.offsetHeight);
    });
    if (maxHeight > 0) {
      cards.forEach(function(card) {
        card.style.height = maxHeight + 'px';
      });
    }
  }

  function matchAllCouncilCardHeights() {
    matchCardHeightsIn('councilCarousel');
    matchCardHeightsIn('councilCarousel2');
  }

  function runWhenReady() {
    matchAllCouncilCardHeights();
    ['councilCarousel', 'councilCarousel2'].forEach(function(id) {
      var carousel = document.getElementById(id);
      if (!carousel) {
        return;
      }
      carousel.querySelectorAll('.thumb img').forEach(function(img) {
        if (img.complete) {
          return;
        }
        img.addEventListener('load', matchAllCouncilCardHeights);
        img.addEventListener('error', matchAllCouncilCardHeights);
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', runWhenReady);
  } else {
    runWhenReady();
  }

  window.addEventListener('resize', matchAllCouncilCardHeights);
})();
</script>
